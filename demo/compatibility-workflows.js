const registered = new WeakSet();
export async function nativeTaskProject(compiler,source) {
  if (!registered.has(compiler)) {
    const url = new URL('./native-command.json',import.meta.url);
    const response = await fetch(url); if (!response.ok) throw new Error(`Native sample failed to load: HTTP ${response.status}`);
    const fixture = await response.json();
    const bytes = Uint8Array.from(atob(fixture.base64),c=>c.charCodeAt(0));
    await compiler.addNativeCommand('native-generator',bytes); registered.add(compiler);
  }
  const files = new Map([
    ['NativeDemo.csproj','<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net10.0</TargetFramework><OutputType>Exe</OutputType><AssemblyName>NativeDemo</AssemblyName></PropertyGroup><Target Name="GenerateNative" BeforeTargets="CoreCompile"><Exec Command="native-generator generate input.txt Generated.cs" EnvironmentVariables="OFFSET=2" /><ItemGroup><Compile Include="Generated.cs" /></ItemGroup></Target></Project>'],
    ['Program.cs',source],['input.txt','40']
  ]);
  return {projectPath:'NativeDemo.csproj',files,restore:false,commandRunner:request=>compiler.runNativeCommand(request.command,request)};
}
