const taskAssemblies = new WeakMap();
export const buildTaskSource = `using System;
using System.IO;
using Microsoft.Build.Framework;
using Microsoft.Build.Utilities;

public sealed class GenerateAnswer : Task
{
    [Required] public string Destination { get; set; } = "";
    [Output] public ITaskItem[] GeneratedFiles { get; private set; } = Array.Empty<ITaskItem>();
    public override bool Execute()
    {
        Directory.CreateDirectory(Path.GetDirectoryName(Destination)!);
        File.WriteAllText(Destination, "public static class TaskGenerated { public const int Answer = 42; }");
        GeneratedFiles = new ITaskItem[] { new TaskItem(Destination) };
        Log.LogMessage(MessageImportance.High, "Generated {0}", Destination);
        return true;
    }
}`;
export async function customTaskProjectFiles(compiler, source) {
  let assembly = taskAssemblies.get(compiler);
  if (!assembly) {
    await compiler.loadTaskReferences();
    assembly = await compiler.compile(buildTaskSource, {assemblyName:'DemoBuildTasks',outputKind:'library',compilerExtensions:[],enableGenerators:false,enableAnalyzers:false});
    if (!assembly.success) throw new Error(JSON.stringify(assembly.diagnostics || assembly.error));
    taskAssemblies.set(compiler, assembly);
  }
  return new Map([
    ['TaskDemo.csproj',`<Project Sdk="Microsoft.NET.Sdk"><PropertyGroup><TargetFramework>net10.0</TargetFramework><OutputType>Exe</OutputType><AssemblyName>TaskDemo</AssemblyName></PropertyGroup><UsingTask TaskName="GenerateAnswer" AssemblyFile="DemoBuildTasks.dll" /><Target Name="GenerateCode" BeforeTargets="CoreCompile"><GenerateAnswer Destination="obj/TaskGenerated.cs"><Output TaskParameter="GeneratedFiles" ItemName="Compile" /></GenerateAnswer></Target></Project>`],
    ['Program.cs',source],
    ['DemoBuildTasks.dll',assembly.pe]
  ]);
}
