// DOTNET=/path/to/dotnet node tests/generate-ordinal-tables.mjs [--update]
import assert from 'node:assert/strict';
import { execFile } from 'node:child_process';
import { promisify } from 'node:util';
import { createHash } from 'node:crypto';
import { copyFile, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { ordinalTableInfo, ordinalUpperPairs } from '../src/il/ordinal-tables.mjs';
const directory=await mkdtemp(join(tmpdir(),'roslynweb-ordinal-tables-'));
try {
 const program=new URL('./ordinal-generator/Program.cs',import.meta.url),project=new URL('./ordinal-generator/OrdinalGenerator.csproj',import.meta.url);
 await Promise.all([copyFile(program,join(directory,'Program.cs')),copyFile(project,join(directory,'Generator.csproj'))]);
 const result=await promisify(execFile)(process.env.DOTNET??'dotnet',['run','--project',join(directory,'Generator.csproj'),'--configuration','Release','--verbosity','quiet','-p:UseSharedCompilation=false'],{encoding:'utf8',timeout:60000,maxBuffer:1024*1024});
 const data=JSON.parse(result.stdout),{mappings,...info}=data;
 info.generatorSha256=createHash('sha256').update(await readFile(program)).update(await readFile(project)).digest('hex');
 if(process.argv.includes('--update')) {
  const rows=[];for(let i=0;i<mappings.length;i+=24)rows.push('  '+mappings.slice(i,i+24).join(',')+',');
  await writeFile(new URL('../src/il/ordinal-tables.mjs',import.meta.url),'/** Generated by tests/ordinal-generator; do not edit by hand. */\nexport const ordinalTableInfo = Object.freeze('+JSON.stringify(info)+');\nexport const ordinalUpperPairs = Object.freeze([\n'+rows.join('\n')+'\n]);\n');
 } else {
  assert.equal(info.scalarCount,ordinalTableInfo.scalarCount);
  assert.equal(info.mappingSha256,ordinalTableInfo.mappingSha256,'Installed CLR/ICU ordinal behavior differs from the pinned table; use the documented runtime/ICU to reproduce or review an explicit table update.');
  assert.deepEqual(mappings,ordinalUpperPairs);
  assert.equal(info.generatorSha256,ordinalTableInfo.generatorSha256,'Generator source changed; review and regenerate table provenance.');
 }
 console.log(`PASS ${info.scalarCount} ordinal inputs, ${info.mappingCount} mappings; .NET ${info.runtime}, ICU ${info.icuVersion}, SHA256 ${info.mappingSha256}.`);
} finally {await rm(directory,{recursive:true,force:true});}
